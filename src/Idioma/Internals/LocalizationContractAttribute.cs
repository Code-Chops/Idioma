namespace CodeChops.Idioma.Internals;

/// <summary>
/// <para>
/// Don't use this attribute directly! It's used by the source generator.
/// </para>
/// <para>
/// Marks an interface as the contract of a set, such as <c>IShopLocalization</c>. The source generator writes this on
/// every contract it generates. The contract doesn't derive from <see cref="ILocalizationSet"/>, so this is how the
/// build recognizes it, in its own assembly and in every assembly that references it. The build then holds each set
/// that implements the contract to its texts.
/// </para>
/// <para>
/// The contract of a set of an enum names its enums, as in <c>[LocalizationContract(typeof(OrderStatus))]</c>. The
/// build then warns about a set of it that doesn't list <see cref="ILocalizationSet{TEnum}"/> of each enum, or that
/// lists another enum (<c>LOC211</c>).
/// </para>
/// </summary>
// Matched by its name and namespaces, part by part, and read by constructor position.
[Obsolete("Don't use this attribute directly. Only generated code should apply this attribute. The source generator writes it on every contract.")]
[EditorBrowsable(EditorBrowsableState.Never)]
[AttributeUsage(AttributeTargets.Interface)]
public sealed class LocalizationContractAttribute : Attribute
{
    /// <summary>
    /// The enums whose members the contract has a text for, which each of its sets lists as
    /// <see cref="ILocalizationSet{TEnum}"/>. Empty for a contract that isn't of an enum.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public IReadOnlyList<Type> Enums { get; }

    /// <summary>
    /// Marks a contract that isn't of an enum. A contract generated by a version of this package before the enums were
    /// named has this too.
    /// </summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public LocalizationContractAttribute()
    {
        this.Enums = [];
    }

    /// <summary>
    /// Marks the contract of a set of one or more enums.
    /// </summary>
    /// <param name="enums">The enums whose members the contract has a text for.</param>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public LocalizationContractAttribute(params Type[] enums)
    {
        ArgumentNullException.ThrowIfNull(enums);

        this.Enums = enums;
    }
}
