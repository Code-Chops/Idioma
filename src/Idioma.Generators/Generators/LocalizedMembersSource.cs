namespace CodeChops.Idioma.Generators;

/// <summary>
/// Writes the texts of the members marked <c>[Localized]</c> (<see cref="LocalizedMembers"/>): a
/// <c>LocalizableText</c> per member, with the wording its attribute gives per language, and one function that finds
/// a member's text by its type and name. The assembly's registrar records that function
/// (<see cref="LocalizationRegistrationPart"/>, which also writes this file), so
/// <c>LocalizableText.GetTextByMember</c> finds the text without reading an attribute at run time. For an enum with a
/// marked member it also writes the extension method that gives a value its text: <c>status.GetText()</c>.
/// </summary>
/// <remarks>
/// <para>
/// Each text has a key, because its member gives it a name. Its full key is the member's full name, such as
/// <c>Shop.Domain.Address.City</c>, and its key is the member's name. A type's own text has the type's full name and
/// name. A type inside another is written with dots, and a type with type parameters keeps its arity
/// (<c>Shop.Domain.Page`1.Items</c>), so that <c>Page</c> and <c>Page&lt;T&gt;</c> don't share keys.
/// </para>
/// <para>
/// The code lies in one file, at the top level of the assembly. A type it can't name from there, which is a private
/// or protected nested type or a file-local one, gets no text, and <c>LocalizedMemberAnalyzer</c> says so
/// (<c>LOC505</c>).
/// </para>
/// <para>
/// The file marks its assembly <c>[assembly: InlineTexts]</c>, because a text on a member carries its wording itself,
/// as an inline text does. So no assembly referencing this one can add a language to it (<c>LOC601</c>).
/// </para>
/// </remarks>
internal static class LocalizedMembersSource
{
    /// <summary>
    /// The name of the file the texts are written to.
    /// </summary>
    public const string HintName = "LocalizedMembers.g.cs";

    /// <summary>
    /// The class that finds the texts, outside the namespace of the class that records them, at the top level of the
    /// file.
    /// </summary>
    private const string OwnMembersName = "OwnLocalizedMembers";

    /// <summary>
    /// The start of the name of a class that holds the texts of one type, which its number ends.
    /// </summary>
    private const string TextsName = "LocalizedTexts";

    private const string OwnTextName = "OwnText";

    public static string Generate(LocalizedMembersModel model)
    {
        var sb = new StringBuilder();

        // The pragma also covers a type or a member of an enum marked [Obsolete] or [Experimental], which this file names
        // for as long as it has a text.
        var warnings = LocalizationRegistrationPart.WithSuppressed(LocalizationRegistrationPart.ObsoleteWarnings, model.SuppressedDiagnostics);

        sb.AppendLine($$"""
            // <auto-generated/>
            #nullable enable
            #pragma warning disable {{warnings}} // Only generated code calls GeneratedCode and applies InlineTexts.

            // The texts below carry their wording themselves, as an inline text does.
            [assembly: {{PackageNames.InlineTextsAttribute}}]

            namespace {{LocalizedMembers.RecorderNamespace}}
            {
                /// <summary>
                /// Records the texts of this assembly's members marked <c>[Localized]</c>, so that <c>LocalizableText.GetTextByMember</c> finds them.
                /// The assembly's registrar calls it.
                /// </summary>
                [System.ComponentModel.EditorBrowsable(System.ComponentModel.EditorBrowsableState.Never)]
                internal static class {{model.RecorderName}}
                {
                    internal static void Register()
                    {
                        {{PackageNames.GeneratedCode}}.RecordMemberTexts(static (type, member) => {{OwnMembersName}}.Find(type, member));
                    }
                }
            }

            /// <summary>
            /// Finds the texts of this assembly's members marked <c>[Localized]</c>. This class is outside the namespace above, so a type's
            /// name is resolved from the global namespace, not from that namespace first.
            /// </summary>
            file static class {{OwnMembersName}}
            {
                /// <summary>
                /// The text of a member of a type, or the type's own text for a member that is <see langword="null"/>.
                /// </summary>
                internal static {{PackageNames.LocalizableText}}? Find(System.Type type, string? member)
                {
            """);

        for (var i = 0; i < model.Types.Length; i++)
        {
            var type = model.Types[i];
            var number = 0;

            sb.AppendLine($$"""
                        if (type == typeof({{type.Reference}}))
                        {
                            return member switch
                            {
                """);

            foreach (var text in type.Texts)
            {
                var pattern = text.MemberName is null ? "null" : SymbolDisplay.FormatLiteral(text.MemberName, quote: true);
                sb.AppendLine($"                {pattern} => {TextsName}{i}.{GetFieldName(text, ref number)},");
            }

            sb.AppendLine("""
                                _ => null,
                            };
                        }

                """);
        }

        sb.AppendLine("""
                    return null;
                }
            }
            """);

        for (var i = 0; i < model.Types.Length; i++)
            AppendTexts(sb, model, i);

        for (var i = 0; i < model.Types.Length; i++)
            if (model.Types[i].Extension is { } extension)
                AppendExtension(sb, extension, i);

        sb.AppendLine($"#pragma warning restore {warnings}");
        sb.AppendLine("#nullable restore");

        return sb.ToString();
    }

    /// <summary>
    /// Writes the class that holds the texts of one type, each created when the class is first used. For an enum it
    /// also holds the text of each value, which the extension method gives.
    /// </summary>
    // The fields are numbered, and not named after their members: a field named like the start of a namespace would
    // stand before that namespace in this class.
    private static void AppendTexts(StringBuilder sb, LocalizedMembersModel model, int index)
    {
        var type = model.Types[index];
        var number = 0;

        sb.AppendLine($$"""

            /// <summary>
            /// The texts of <c>{{LocalizationSetsPart.EscapeXml(type.Reference)}}</c>.
            /// </summary>
            file static class {{TextsName}}{{index}}
            {
            """);

        foreach (var text in type.Texts)
        {
            var fullKey = text.MemberName is null ? type.Key : $"{type.Key}.{text.MemberName}";
            var key = text.MemberName ?? type.Name;
            var wordings = String.Join(", ", model.Codes.Select((code, language) =>
                $"({SymbolDisplay.FormatLiteral(code, quote: true)}, {SymbolDisplay.FormatLiteral(text.Wordings[language], quote: true)})"));

            sb.AppendLine($"    internal static readonly {PackageNames.LocalizableText} {GetFieldName(text, ref number)} = {PackageNames.GeneratedCode}.CreateMemberText({SymbolDisplay.FormatLiteral(fullKey, quote: true)}, {SymbolDisplay.FormatLiteral(key, quote: true)}, {wordings});");
        }

        if (type.Extension is not null)
        {
            sb.AppendLine($$"""

                    internal static {{PackageNames.LocalizableText}} Get({{type.Reference}} value) => value switch
                    {
                """);

            // Of two members of one value, the first gives its text: a switch takes a value once.
            var values = new HashSet<string>(StringComparer.Ordinal);
            number = 0;

            foreach (var text in type.Texts)
            {
                var field = GetFieldName(text, ref number);

                if (text.MemberName is not null && (text.EnumValue is null || values.Add(text.EnumValue)))
                    sb.AppendLine($"        {type.Reference}.{LocalizationSetsPart.EscapeIdentifier(text.MemberName)} => {field},");
            }

            sb.AppendLine($$"""
                        _ => {{PackageNames.GeneratedCode}}.CreateUndefinedEnumText<{{type.Reference}}>(value),
                    };
                """);
        }

        sb.AppendLine("}");
    }

    /// <summary>
    /// Writes the extension method that gives a value of an enum its text, in a class in the enum's namespace, so
    /// that the method is in reach wherever the enum is.
    /// </summary>
    private static void AppendExtension(StringBuilder sb, LocalizedEnumExtension extension, int index)
    {
        var accessibility = extension.IsPublic ? "public" : "internal";
        var hasNamespace = extension.Namespace.Length > 0;
        var indent = hasNamespace ? "    " : "";

        var enumLink = $"<see cref=\"{extension.EnumName}\"/>";

        sb.AppendLine();

        if (hasNamespace)
        {
            sb.AppendLine($"namespace {extension.Namespace}");
            sb.AppendLine("{");
        }

        var holder = $$"""
            /// <summary>
            /// Gives a value of {{enumLink}} its text, as in <c>status.{{LocalizedMembers.ExtensionName}}()</c>.
            /// </summary>
            {{accessibility}} static class {{extension.HolderName}}
            {
                /// <param name="value">The value to give the text of.</param>
                extension({{extension.EnumName}} value)
                {
                    /// <summary>
                    /// The text of this value of {{enumLink}}, which the <c>[Localized]</c> of its member words.
                    /// </summary>
                    /// <remarks>
                    /// A value without such a member shows as <c>ToString()</c> writes it. That's a member that isn't marked, or a value that isn't a
                    /// member, such as a combination of flags.
                    /// </remarks>
                    {{accessibility}} {{PackageNames.LocalizableText}} {{LocalizedMembers.ExtensionName}}() => {{TextsName}}{{index}}.Get(value);
                }
            }
            """;

        foreach (var line in holder.Split('\n'))
            sb.AppendLine(line.Length is 0 ? line : indent + line.TrimEnd('\r'));

        if (hasNamespace)
            sb.AppendLine("}");
    }

    /// <summary>
    /// The field of a text in the class of its type: the type's own text by name, and each member by its number.
    /// </summary>
    private static string GetFieldName(LocalizedText text, ref int number)
    {
        var name = text.MemberName is null ? OwnTextName : $"Text{number++}";
        return name;
    }
}
