namespace CodeChops.Idioma.Generators;

/// <summary>
/// Writes the file that records every set of a public contract in an assembly attribute
/// (<see cref="ProvidedLocalizationSet"/>), which the build of an assembly referencing this one reads.
/// </summary>
internal static class ProvidedSetsSource
{
    public static string Generate(EquatableArray<ProvidedLocalizationSet> sets)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine(GeneratedFile.DisableWarnings(GeneratedFile.ObsoleteWarnings, "Only generated code applies LocalizationSet."));

        foreach (var set in sets)
            sb.AppendLine($"[assembly: {PackageNames.LocalizationSetAttribute}({SymbolDisplay.FormatLiteral(set.Contract, quote: true)}, {SymbolDisplay.FormatLiteral(set.Language, quote: true)})]");

        sb.AppendLine(GeneratedFile.RestoreWarnings(GeneratedFile.ObsoleteWarnings));

        return sb.ToString();
    }
}
