namespace CodeChops.Idioma.Generators;

/// <summary>
/// Lists every set of a public contract in an assembly attribute, with what it derives from, for the build of a
/// referencing assembly.
/// </summary>
internal static class ProvidedSetsSource
{
    public static string Generate(EquatableArray<ProvidedLocalizationSet> sets)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine(GeneratedFile.DisableWarnings(GeneratedFile.ObsoleteWarnings, "Only generated code applies LocalizationSet."));

        // The bases last, as the attribute's params array.
        foreach (var set in sets)
        {
            var arguments = new[] { set.Contract, set.Language, set.Set }
                .Select(static argument => SymbolDisplay.FormatLiteral(argument, quote: true))
                .Append(set.Reworded is null ? "null" : SymbolDisplay.FormatLiteral(set.Reworded, quote: true))
                .Concat(set.Bases.Select(static name => SymbolDisplay.FormatLiteral(name, quote: true)));

            sb.AppendLine($"[assembly: {PackageNames.LocalizationSetAttribute}({String.Join(", ", arguments)})]");
        }

        sb.AppendLine(GeneratedFile.RestoreWarnings(GeneratedFile.ObsoleteWarnings));

        return sb.ToString();
    }
}
